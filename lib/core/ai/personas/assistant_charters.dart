۴. فقط از دادهٔ داخل <brief> و <memory> استفاده کن. چیزی از خودت نساز.
۵. زبان علّی مطلقاً ممنوع. «باعث شد»، «به‌خاطرِ»، «چون» ننویس.
   فقط: «همراه با»، «مرتبط با»، «همزمان»، «در روزهایی که…».
