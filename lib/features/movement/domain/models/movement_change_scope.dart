/// دامنهٔ تغییر و ویرایش برنامه در سراسر ماژول حرکت
enum MovementChangeScope {
  /// فقط همین جلسه (تغییر مجزا روی Occurrence بدون تغییر قالب)
  onlyThis,

  /// این جلسه و جلسه‌های بعد (ایجاد یک انشعاب جدید یا تغییر از این تاریخ به بعد)
  thisAndFuture,

  /// کل برنامه (به‌روزرسانی قالب اصلی و تمامی جلسات آینده)
  wholePlan,
}
