import 'dart:math' as math;

/// Phase of a goal-oriented training campaign (S5-T2).
enum MvCampaignPhase {
  base,
  progressiveLoad,
  taper,
}

/// Target parameters for a single week of a campaign.
class MvCampaignWeekPlan {
  final int weekNumber; // 1-indexed (1..totalWeeks)
  final MvCampaignPhase phase;
  final double packWeightPercent; // e.g. 0.0, 0.05, 0.10, 0.15, 0.20
  final double packWeightKg; // packWeightPercent * bodyWeightKg
  final double volumeRatio; // e.g. 1.0 (normal) or 0.6 (taper)
  final String reasonKey;
  final Map<String, dynamic> reasonParams;
  final bool isTaper;

  const MvCampaignWeekPlan({
    required this.weekNumber,
    required this.phase,
    required this.packWeightPercent,
    required this.packWeightKg,
    this.volumeRatio = 1.0,
    required this.reasonKey,
    this.reasonParams = const {},
    this.isTaper = false,
  });
}

/// Overall campaign schedule output generated by CampaignEngine.
class MvCampaignPlan {
  final int totalWeeks;
  final double userBodyWeightKg;
  final List<MvCampaignWeekPlan> weeks;
  final String? warningKey;
  final bool isTooShort;

  const MvCampaignPlan({
    required this.totalWeeks,
    required this.userBodyWeightKg,
    required this.weeks,
    this.warningKey,
    this.isTooShort = false,
  });

  /// Helper to get plan for a specific 1-indexed week.
  MvCampaignWeekPlan? getWeekPlan(int weekNumber) {
    if (weekNumber < 1 || weekNumber > weeks.length) return null;
    return weeks[weekNumber - 1];
  }
}

/// 7.12 CampaignEngine: Deterministic reverse-periodization engine for goal events (S5-T2).
/// Pure Dart — No UI or Database dependencies.
class CampaignEngine {
  const CampaignEngine();

  static const List<double> _packSteps = [0.05, 0.10, 0.15, 0.20];

  /// Builds the full multi-week progression plan for an OUTDOOR/HIKING goal.
  MvCampaignPlan buildOutdoorPlan({
    required int totalWeeks,
    required double bodyWeightKg,
  }) {
    final effectiveWeight = bodyWeightKg > 0 ? bodyWeightKg : 70.0;

    if (totalWeeks < 4) {
      // Too short: base + taper only, with warning
      final weeks = <MvCampaignWeekPlan>[];
      for (int w = 1; w <= totalWeeks; w++) {
        if (w == totalWeeks) {
          // Last week is taper
          weeks.add(
            MvCampaignWeekPlan(
              weekNumber: w,
              phase: MvCampaignPhase.taper,
              packWeightPercent: 0.0,
              packWeightKg: 0.0,
              volumeRatio: 0.6,
              reasonKey: 'mv_campaign_taper',
              reasonParams: {'week': w},
              isTaper: true,
            ),
          );
        } else {
          // Base
          weeks.add(
            MvCampaignWeekPlan(
              weekNumber: w,
              phase: MvCampaignPhase.base,
              packWeightPercent: 0.0,
              packWeightKg: 0.0,
              volumeRatio: 1.0,
              reasonKey: 'mv_campaign_base',
              reasonParams: {'week': w},
              isTaper: false,
            ),
          );
        }
      }

      return MvCampaignPlan(
        totalWeeks: totalWeeks,
        userBodyWeightKg: effectiveWeight,
        weeks: weeks,
        warningKey: 'mv_campaign_too_short',
        isTooShort: true,
      );
    }

    // Standard totalWeeks >= 4
    // Phase 1: Base (first 4 weeks or half of (totalWeeks - 1), whichever is less)
    final baseWeeks = math.min(4, (totalWeeks - 1) ~/ 2);
    final weeks = <MvCampaignWeekPlan>[];

    for (int w = 1; w <= totalWeeks; w++) {
      if (w == totalWeeks) {
        // Phase 3: Taper (1 week before event)
        weeks.add(
          MvCampaignWeekPlan(
            weekNumber: w,
            phase: MvCampaignPhase.taper,
            packWeightPercent: 0.0,
            packWeightKg: 0.0,
            volumeRatio: 0.6,
            reasonKey: 'mv_campaign_taper',
            reasonParams: {'week': w},
            isTaper: true,
          ),
        );
      } else if (w <= baseWeeks) {
        // Phase 1: Base building — 0 pack weight
        weeks.add(
          MvCampaignWeekPlan(
            weekNumber: w,
            phase: MvCampaignPhase.base,
            packWeightPercent: 0.0,
            packWeightKg: 0.0,
            volumeRatio: 1.0,
            reasonKey: 'mv_campaign_base',
            reasonParams: {'week': w},
            isTaper: false,
          ),
        );
      } else {
        // Phase 2: Progressive pack weight (5% -> 10% -> 15% -> 20%, 2 weeks each step)
        final phase2Index = w - (baseWeeks + 1);
        final stepIndex = (phase2Index ~/ 2).clamp(0, _packSteps.length - 1);
        final packPercent = _packSteps[stepIndex];
        final packKg = double.parse((packPercent * effectiveWeight).toStringAsFixed(1));

        weeks.add(
          MvCampaignWeekPlan(
            weekNumber: w,
            phase: MvCampaignPhase.progressiveLoad,
            packWeightPercent: packPercent,
            packWeightKg: packKg,
            volumeRatio: 1.0,
            reasonKey: 'mv_campaign_progressive_load',
            reasonParams: {'week': w, 'packKg': packKg, 'percent': (packPercent * 100).toInt()},
            isTaper: false,
          ),
        );
      }
    }

    return MvCampaignPlan(
      totalWeeks: totalWeeks,
      userBodyWeightKg: effectiveWeight,
      weeks: weeks,
      warningKey: null,
      isTooShort: false,
    );
  }
}
